import {
  type OpportunityInput,
  OpportunityInputSchema,
  type ProviderMeta,
  ProviderMetaSchema,
} from '@unneet/domain';

/**
 * Evergreen national schemes, free learning and support services, written and link-checked by
 * hand (see scripts/check-links.ts). These are NOT time-limited vacancies: they are the "front
 * doors" every young person should know about. Live vacancies come from provider adapters.
 *
 * Writing rules: plain English; say who it's for and what it costs; never overstate. If an age or
 * eligibility rule matters it must come from the official page, and funded schemes always say
 * "check you're eligible".
 */
export const CURATED_PROVIDER: ProviderMeta = ProviderMetaSchema.parse({
  id: 'curated',
  name: 'UnNEET editorial',
  licence: 'Editorial content by UnNEET. Links go to the official source.',
  attribution: 'Described by UnNEET. Always check the official page for the latest details.',
  attributionUrl: null,
  storagePolicy: 'store',
  isSample: false,
  requiresKey: false,
});

type Draft = Omit<OpportunityInput, 'location' | 'organisation' | 'cost'> & {
  org: string;
  orgUrl?: string;
  where?: 'nationwide' | 'online' | 'england' | 'scotland' | 'wales' | 'northern-ireland';
  cost?: OpportunityInput['cost'];
};

const toInput = (d: Draft): OpportunityInput => {
  const { org, orgUrl, where = 'nationwide', cost, ...rest } = d;
  const country = ['england', 'scotland', 'wales', 'northern-ireland'].includes(where)
    ? (where as 'england' | 'scotland' | 'wales' | 'northern-ireland')
    : 'uk';
  const label =
    where === 'online'
      ? 'Online'
      : where === 'nationwide'
        ? 'UK-wide'
        : where === 'northern-ireland'
          ? 'Northern Ireland'
          : where.charAt(0).toUpperCase() + where.slice(1);
  return {
    ...rest,
    organisation: { name: org, url: orgUrl ?? null },
    cost: cost ?? { kind: 'free', amount: null },
    location: {
      label,
      workMode: where === 'online' ? 'remote' : 'nationwide',
      country,
    },
  };
};


/** Deterministic PRNG (mulberry32) so seed output is identical every run: stable URLs, stable tests. */
function rng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const DAY = 86_400_000;

function employer(sector: Sector, i: number): string {
  const stem = EMPLOYER_STEMS[i % EMPLOYER_STEMS.length] as string;
  const noun = sector.name.split(/[ ,]/)[0] as string;
  return `Sample: ${stem} ${noun} Ltd`;
}

const describe = (role: string, org: string, city: string, extra: string): string =>
  `Sample listing for demonstration only. This is not a real vacancy.\n\n${role} with ${org} in ${city}. ${extra}\n\nYou will be part of a friendly team, with training from day one and plenty of support to help you settle in.`;

/** ~100 varied, deterministic demo listings spread over 12 cities and all 15 sectors. */
export function generateSample(now: Date): OpportunityInput[] {
  const out: OpportunityInput[] = [];
  let n = 0;

  SECTORS.forEach((sector, sectorIndex) => {
    const random = rng(1000 + sectorIndex);
    const pick = <T>(list: readonly T[]): T => list[Math.floor(random() * list.length)] as T;
    const common = (type: OpportunityInput['type']) => {
      n += 1;
      const city = pick(CITIES);
      const jitter = () => (random() - 0.5) * 0.12; // spread within the city
      const org = employer(sector, n);
      return {
        city,
        org,
        externalId: `sample-${String(n).padStart(3, '0')}`,
        postedAt: new Date(now.getTime() - Math.floor(random() * 21) * DAY).toISOString(),
        closesAt: new Date(now.getTime() + (7 + Math.floor(random() * 38)) * DAY).toISOString(),
        location: {
          label: city.name,
          lat: Math.round((city.lat + jitter()) * 1e5) / 1e5,
          lon: Math.round((city.lon + jitter()) * 1e5) / 1e5,
          region: city.region,
          country: city.country,
          workMode: (type === 'course' && random() < 0.4 ? 'remote' : 'onsite') as
            | 'remote'
            | 'onsite',
        },
      };
    };

    // 3 jobs
    for (const role of sector.exampleRoles.slice(0, 3)) {
      const c = common('job');
      const level = pick([0, 1, 2, 2, 3] as const);
      const hourly = Math.round((11.4 + random() * 5 + level * 1.2) * 100) / 100;
      out.push({
        externalId: c.externalId,
        type: 'job',
        title: role,
        description: describe(
          role,
          c.org,
          c.city.name,
          `Full-time and part-time shifts available. ${level === 0 ? 'No experience needed: full training provided.' : 'Some experience is helpful but not essential.'}`,
        ),
        organisation: { name: c.org, url: null },
        applyUrl: `https://example.com/sample/${c.externalId}`,
        sector: sector.slug,
        level,
        minEntryLevel: level <= 1 ? 0 : level,
        location: c.location,
        pay: {
          min: hourly,
          max: Math.round((hourly + 1.5) * 100) / 100,
          unit: 'hour',
          isEstimate: false,
        },
        cost: { kind: 'free', amount: null },
        postedAt: c.postedAt,
        closesAt: c.closesAt,
        tags: level === 0 ? ['no-experience', 'no-qualifications'] : [],
        experienceRequired: level === 0 ? false : null,
      });
    }

    // 1 apprenticeship
    {
      const c = common('apprenticeship');
      const level = pick([2, 3] as const);
      const role = `${sector.exampleRoles[0]} apprentice (Level ${level})`;
      out.push({
        externalId: c.externalId,
        type: 'apprenticeship',
        title: role,
        description: describe(
          role,
          c.org,
          c.city.name,
          'Earn a wage while you train, with day-release study and a nationally recognised qualification at no cost to you.',
        ),
        organisation: { name: c.org, url: null },
        applyUrl: `https://example.com/sample/${c.externalId}`,
        sector: sector.slug,
        level,
        minEntryLevel: level - 1,
        minAge: 16,
        location: c.location,
        pay: {
          min: 7.55 + level * 0.5,
          max: 8.5 + level * 0.8,
          unit: 'hour',
          isEstimate: false,
          note: 'Sample figure',
        },
        cost: { kind: 'free', amount: null },
        duration: level === 2 ? '15 months' : '24 months',
        postedAt: c.postedAt,
        closesAt: c.closesAt,
        tags: ['accredited', 'government-funded'],
      });
    }

    // 1 course (free, funded or paid depending on sector)
    {
      const c = common('course');
      const mode = sectorIndex % 3;
      const level = pick([1, 2, 3] as const);
      const role = `${sector.name.split(',')[0]} Level ${level} Certificate`;
      out.push({
        externalId: c.externalId,
        type: 'course',
        title: role,
        description: describe(
          role,
          c.org,
          c.city.name,
          'A short, practical course with flexible evening and weekend classes.',
        ),
        organisation: { name: c.org, url: null },
        applyUrl: `https://example.com/sample/${c.externalId}`,
        sector: sector.slug,
        level,
        minEntryLevel: Math.max(0, level - 1),
        location: c.location,
        cost:
          mode === 0
            ? { kind: 'free', amount: null }
            : mode === 1
              ? { kind: 'funded', amount: null, note: 'Free if you qualify. Check eligibility.' }
              : { kind: 'paid', amount: 400 + Math.floor(random() * 1800) },
        duration: `${6 + Math.floor(random() * 20)} weeks`,
        postedAt: c.postedAt,
        closesAt: c.closesAt,
        tags: ['accredited'],
      });
    }
  });

  // A few extras for variety: volunteering, traineeship, internship, remote job.
  const extras: Array<
    Pick<OpportunityInput, 'type' | 'title'> & {
      sector: Sector['slug'];
      city: number;
      remote?: boolean;
    }
  > = [
    { type: 'volunteering', title: 'Community care volunteer', sector: 'care-services', city: 0 },
    {
      type: 'volunteering',
      title: 'Animal shelter helper',
      sector: 'agriculture-environment-animal-care',
      city: 4,
    },
    {
      type: 'traineeship',
      title: 'Retail traineeship with work placement',
      sector: 'sales-marketing-procurement',
      city: 2,
    },
    {
      type: 'traineeship',
      title: 'Hospitality traineeship',
      sector: 'catering-hospitality',
      city: 7,
    },
    {
      type: 'internship',
      title: 'Digital marketing intern',
      sector: 'sales-marketing-procurement',
      city: 3,
    },
    { type: 'internship', title: 'Software engineering summer intern', sector: 'digital', city: 3 },
    {
      type: 'job',
      title: 'Remote customer support advisor',
      sector: 'business-administration',
      city: 0,
      remote: true,
    },
    {
      type: 'job',
      title: 'Remote data entry assistant',
      sector: 'business-administration',
      city: 1,
      remote: true,
    },
  ];
  extras.forEach((e, i) => {
    const sector = SECTORS.find((s) => s.slug === e.sector) as Sector;
    const city = CITIES[e.city] as City;
    const id = `sample-x${String(i + 1).padStart(2, '0')}`;
    const org = employer(sector, 40 + i);
    out.push({
      externalId: id,
      type: e.type,
      title: e.title,
      description: describe(e.title, org, city.name, 'Flexible hours around other commitments.'),
      organisation: { name: org, url: null },
      applyUrl: `https://example.com/sample/${id}`,
      sector: sector.slug,
      level: e.type === 'internship' ? 4 : 1,
      minEntryLevel: e.type === 'internship' ? 3 : 0,
      location: e.remote
        ? { label: 'Online', workMode: 'remote', country: 'uk' }
        : {
            label: city.name,
            lat: city.lat,
            lon: city.lon,
            region: city.region,
            country: city.country,
            workMode: 'onsite',
          },
      pay: e.type === 'job' ? { min: 12.1, max: 12.1, unit: 'hour', isEstimate: false } : null,
      cost: { kind: 'free', amount: null },
      postedAt: new Date(now.getTime() - (i + 1) * DAY).toISOString(),
      closesAt: new Date(now.getTime() + (20 + i) * DAY).toISOString(),
      tags: e.type === 'volunteering' || e.type === 'traineeship' ? ['no-experience'] : [],
    });
  });
  return out;
}

export const sampleAdapter: ProviderAdapter = {
  meta: SAMPLE_PROVIDER,
  fullFeed: true,
  isConfigured: () => true,
  async *fetch(ctx) {
    for (const o of generateSample(ctx.now)) yield o;
  },
  map(raw): Mapped {
    return { ok: true, input: raw as OpportunityInput };
  },
};

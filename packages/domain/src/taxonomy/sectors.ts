const BY_SLUG = new Map<SectorSlug, Sector>(SECTORS.map((s) => [s.slug, s]));

export function getSector(slug: SectorSlug): Sector {
  const sector = BY_SLUG.get(slug);
  if (!sector) throw new Error(`Unknown sector: ${slug}`);
  return sector;
}

export function isSectorSlug(value: unknown): value is SectorSlug {
  return typeof value === 'string' && BY_SLUG.has(value as SectorSlug);
}

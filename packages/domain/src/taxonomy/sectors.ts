/** Holland / RIASEC interest types. */
export const RIASEC_TYPES = ['R', 'I', 'A', 'S', 'E', 'C'] as const;
export type RiasecType = (typeof RIASEC_TYPES)[number];
export type RiasecVector = Record<RiasecType, number>;

export interface Sector {
  slug: SectorSlug;
  /** Official Skills England route name. */
  name: string;
  /** One plain-English sentence aimed at a reading age of ~10. */
  blurb: string;
  /** Example roles to make the sector concrete for someone who has never worked in it. */
  exampleRoles: readonly string[];
  /**
   * Heuristic interest profile (0–1 per RIASEC type) used to turn a quiz result into sector fit.
   * AUTHORED PRIOR, not a measured value: derived by hand from O*NET occupational interest
   * profiles for typical roles in each route. Treat as a starting point to calibrate, see
   * docs/ARCHITECTURE.md §8.
   */
  riasec: RiasecVector;
  /** Lower-case keywords used by the text classifier (see classify/sector.ts). */
  keywords: readonly string[];
}

